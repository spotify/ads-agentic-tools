def code(currency, amount_first=False):
    if amount_first:
        return regex(rf"'\d[\d.,]* {currency}\b'")
    return regex(rf"'\b{currency} \d'")


def term(banned):
    return regex(rf"'\b({banned})\b'", flags="i", absent=True)


def enum_absent(value):
    return regex(rf"'\b{value}\b'", absent=True, weight=2)


def display(text, case_sensitive=True):
    return regex(f"'{text}'", flags=None if case_sensitive else "i")


