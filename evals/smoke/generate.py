def report(rows, start="2026-09-01T00:00:00Z", end="2026-10-01T00:00:00Z"):
    """rows: [(entity_type, id, name, status, {FIELD: value})]."""
    return {"report_start": start, "report_end": end, "rows": [
        {"entity_type": t, "entity_id": i, "entity_name": n, "entity_status": s,
         "start_time": start, "end_time": end,
         "stats": [{"field_type": k, "field_value": v} for k, v in stats.items()]}
        for t, i, n, s, stats in rows]}


def totals(stats, start="2026-09-01T00:00:00Z", end="2026-10-01T00:00:00Z"):
    return {"report_start": start, "report_end": end,
            "stats": [{"field_type": k, "field_value": v} for k, v in stats.items()]}


def not_found():
    # Same shape as the real API's 404 body (recorded).
    return 404, {"errorCodes": [], "messages": ["Resource not found"]}


