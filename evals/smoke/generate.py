def frontmatter(d):
    lines = []
    for k, v in d.items():
        if k == "body":
            continue
        lines.append(f"{k}: {v}")
    return "---\n" + "\n".join(lines) + "\n---\n"


def write_row(row_id, spec):
    root = os.path.join(HERE, row_id)
    if os.path.isdir(root):
        for sub in ("api", "graders"):
            shutil.rmtree(os.path.join(root, sub), ignore_errors=True)
    os.makedirs(os.path.join(root, "graders"), exist_ok=True)

    tags = ["smoke", spec["principle"].split()[0] if not spec["principle"].startswith("LS") else "enum_display",
            spec["group"], "regression" if not spec["no_api"] else "capability", *spec["tags"]]
    tools = ["Read", "Glob", "Grep", "Skill"] + ([] if spec["no_api"] else ["Bash"])
    env = "" if spec["no_api"] else "env:\n  EVAL_ADS_API_FIXTURES: .git/ads-cache\n"
    with open(os.path.join(root, "prompt.md"), "w") as f:
        description = json.dumps(f"Sheet {row_id}. {spec['expected']}", ensure_ascii=False)
        f.write(f"---\ndescription: {description}\n"
                f"tags: [{', '.join(dict.fromkeys(tags))}]\nmax_turns: 30\ntimeout_seconds: 600\n"
                f"allowed_tools: [{', '.join(tools)}]\n{env}---\n\n{spec['prompt']}\n")

    if not spec["no_api"]:
        os.makedirs(os.path.join(root, "api"), exist_ok=True)
        api = dict(spec["api"])
        if spec["account_over"]:
            api[f"GET__ad_accounts__{A}"] = (200, account(**spec["account_over"]))
        for key, (status, body) in api.items():
            with open(os.path.join(root, "api", f"{key}.http"), "w") as f:
                f.write(f"{status}\n{json.dumps(body, ensure_ascii=False) if body is not None else ''}\n")
        context = "  scaffold_script: scaffold.sh\n" + ("  history_file: history.jsonl\n" if spec["history"] else "")
        with open(os.path.join(root, "case.yaml"), "w") as f:
            f.write(f'schema_version: "1.1"\nname: {row_id}\ncontext:\n{context}')
        settings = spec["settings"] or "settings.local.md"
        with open(os.path.join(root, "scaffold.sh"), "w") as f:
            f.write('#!/bin/bash\nset -euo pipefail\nHERE="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"\n'
                    f'bash "$HERE/../../fixtures/scaffold.sh" {row_id} {settings} "$HERE/api"\n')
        os.chmod(os.path.join(root, "scaffold.sh"), 0o755)

    for name, g in spec["graders"].items():
        if spec["ask"] and name == "no-trailing-question":
            continue
        with open(os.path.join(root, "graders", f"{name}.md"), "w") as f:
            f.write(frontmatter(g) + g.get("body", ""))


if __name__ == "__main__":
    wanted = sys.argv[1:] or list(ROWS)
    for row_id in wanted:
        write_row(row_id, ROWS[row_id])
        print(f"wrote {row_id}")
