# --- graders -----------------------------------------------------------------

def regex(pattern, target=None, absent=False, flags=None, weight=None, count=None):
    g = {"type": "regex", "pattern": pattern}
    if target:
        g["target"] = target
    if flags:
        g["flags"] = flags
    if absent:
        g["match"] = "not_contains"
    if count is not None:
        g["match"] = f'"count:{count}"'
    if weight:
        g["weight"] = weight
    return g


def judge(rubric, weight=None):
    g = {"type": "llm", "body": rubric.strip() + "\n"}
    if weight:
        g["weight"] = weight
    return g


