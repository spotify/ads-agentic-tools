def uid(row, n):
    """Stable, obviously invented UUIDs per row."""
    digits = "".join(c for c in row if c.isdigit()).ljust(4, "0")[:4]
    return f"{digits}{n:04d}-0000-4000-8000-{digits}{n:08d}"


def page(kind, items):
    return {"paging": {"page_size": 50, "total_results": len(items), "offset": 0,
                       "current_page": 1}, kind: items}


